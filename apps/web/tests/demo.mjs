import assert from 'node:assert/strict';
import {mkdir,rename,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../..',import.meta.url));
if(!process.env.SOWCAST_DEMO_OUTPUT) throw new Error('Set SOWCAST_DEMO_OUTPUT to a folder outside the checkout');
const output=path.resolve(process.env.SOWCAST_DEMO_OUTPUT);
const relative=path.relative(root,output);
if(relative==='' || (!relative.startsWith('..'+path.sep) && relative!=='..' && !path.isAbsolute(relative))) throw new Error('Recording output must be outside the checkout');
const {chromium}=await import('playwright');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:process.env.SOWCAST_BROWSER_CHANNEL||'msedge'});
const context=await browser.newContext({viewport:{width:1280,height:720},reducedMotion:'reduce',recordVideo:{dir:path.join(output,'.recording'),size:{width:1280,height:720}}});
const page=await context.newPage();
const started=Date.now();
const events=[];
const mark=label=>events.push({seconds:Math.round((Date.now()-started)/1000),label});
const hold=ms=>page.waitForTimeout(ms);
async function plot(base){
  await page.goto(base);
  await page.getByLabel('Latitude',{exact:true}).fill('13.14');
  await page.getByLabel('Longitude',{exact:true}).fill('78.13');
  await page.getByLabel('Crop',{exact:true}).selectOption('ragi');
  await page.waitForFunction(()=>document.querySelector('#district')?.value==='Kolar');
}
try{
  await plot('http://127.0.0.1:5173');
  mark('Kolar pin and automatic district; unsown ragi');
  await page.getByLabel('Crop',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(output,'plot-phone-context.png')});
  await hold(9000);
  await page.getByRole('button',{name:'Read the field plan'}).click();
  await page.getByRole('heading',{name:'Dates to keep in view'}).waitFor({timeout:60000});
  await page.locator('.forecast-section').scrollIntoViewIfNeeded();
  await hold(18000);mark('Real forecast and separate historical baseline');
  await page.locator('.actions-section').scrollIntoViewIfNeeded();
  await hold(7000);
  await page.getByText('Why this task?',{exact:true}).first().click();
  await page.locator('.action-row').first().scrollIntoViewIfNeeded();
  await hold(18000);mark('Weather-only ragi task and cited inputs');
  await page.getByRole('button',{name:'Ask',exact:true}).click();
  await page.getByLabel('Your question').fill('What evidence should I check before sowing?');
  await hold(5000);
  await page.getByRole('button',{name:'Ask Sowcast'}).click();
  await page.getByRole('heading',{name:/Agent unavailable|Evidence-linked answer/}).waitFor({timeout:60000});
  await page.getByText('Agent trace',{exact:true}).click();
  await page.getByRole('cell',{name:'get_forecast',exact:true}).waitFor();
  await page.locator('main section').scrollIntoViewIfNeeded();
  await hold(18000);mark('Actual Ask result and protected execution trace');
  await page.getByRole('button',{name:'Reliability',exact:true}).click();
  await page.getByRole('heading',{name:'GFS model: rain or no rain agreement'}).waitFor({timeout:60000});
  await hold(9000);
  await page.getByLabel('Rain definition',{exact:true}).selectOption('ge1');
  await page.getByRole('region',{name:'GFS model rain samples, ERA5 base rate and majority baseline'}).scrollIntoViewIfNeeded();
  await hold(16000);mark('Real GFS/ERA5 reliability, threshold and sample counts');
  await plot('http://127.0.0.1:5174');
  await page.getByRole('button',{name:'Read the field plan'}).click();
  await page.getByRole('heading',{name:'A pause in the data.'}).waitFor();
  assert((await page.locator('main').innerText()).includes('No replacement weather or plan has been supplied.'));
  await hold(14000);mark('Isolated source-outage server: typed failure and request ID');
  await plot('http://127.0.0.1:5173');
  await page.getByRole('button',{name:'Read the field plan'}).click();
  await page.getByRole('heading',{name:'Dates to keep in view'}).waitFor({timeout:60000});
  await page.locator('.actions-section').scrollIntoViewIfNeeded();
  await hold(Math.max(5000,150000-(Date.now()-started)));
  mark('Normal app continues independently; recording ends');
  await context.close();
  const target=path.join(output,'Sowcast-local-demo-silent.webm');
  await rename(await page.video().path(),target);
  await writeFile(path.join(output,'demo-timeline.json'),JSON.stringify({recorded_at:new Date().toISOString(),duration_seconds:Math.round((Date.now()-started)/1000),audio:false,data:'Real local API responses; isolated source-outage server only for failure section',events},null,2)+'\n');
  console.log('PASS real, unedited local demo recorded; silent video and timeline saved to the selected folder');
}finally{await context.close();await browser.close();}
