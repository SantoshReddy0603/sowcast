import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base=process.env.SOWCAST_WEB_URL || 'http://127.0.0.1:5173';
const browser=await chromium.launch({headless:true,...(process.env.SOWCAST_BROWSER_CHANNEL ? {channel:process.env.SOWCAST_BROWSER_CHANNEL} : {})});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(()=>{
  Object.defineProperty(window,'SpeechRecognition',{value:undefined,writable:true,configurable:true});
  Object.defineProperty(window,'webkitSpeechRecognition',{value:undefined,writable:true,configurable:true});
});
try {
  await page.goto(base);
  await page.getByRole('heading',{level:1}).waitFor();
  await page.keyboard.press('Tab');
  assert.equal(await page.locator(':focus').innerText(),'Skip to main content');
  await page.getByLabel('Latitude',{exact:true}).fill('13.14');
  await page.getByLabel('Longitude',{exact:true}).fill('78.13');
  await page.getByLabel('Crop',{exact:true}).selectOption('maize');
  await page.waitForFunction(()=>document.querySelector('#district')?.value==='Kolar');
  await page.getByRole('button',{name:'Read the field plan'}).click();
  await page.getByRole('heading',{name:'Dates to keep in view'}).waitFor({timeout:60000});
  await page.getByRole('button',{name:'Ask',exact:true}).click();
  assert(await page.getByRole('button',{name:'Use microphone'}).isDisabled());
  assert((await page.locator('main').innerText()).includes('Voice input is unavailable in this browser. Type your question.'));
  await page.getByLabel('Your question').fill('What field evidence should I check?');
  await page.getByLabel('Answer language').selectOption('kn');
  const nextAnswer=page.waitForResponse(r=>r.url().endsWith('/v1/chat')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Ask Sowcast'}).click();
  const response=await nextAnswer;
  assert.equal(response.status(),200);
  const answer=await response.json();
  await page.getByRole('heading',{name:answer.status==='verified'?'Evidence-linked answer':'Agent unavailable',exact:true}).waitFor();
  assert(answer.trace_access_token&&answer.trace_id);
  assert.equal((await page.request.get(`${base}/v1/traces/${answer.trace_id}`)).status(),404);
  await page.getByText('Agent trace',{exact:true}).click();
  await page.getByRole('cell',{name:'get_forecast',exact:true}).waitFor();
  await page.getByRole('cell',{name:'run_risk_assessment',exact:true}).waitFor();
  assert(!(await page.locator('body').innerText()).includes(answer.trace_access_token));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'test-results/ask-protected-trace.png',fullPage:true});
  await page.getByRole('button',{name:'Delete this trace'}).click();
  await page.getByText('Trace deleted from this server.',{exact:true}).waitFor();
  assert.equal((await page.request.get(`${base}/v1/traces/${answer.trace_id}`,{headers:{Authorization:`Bearer ${answer.trace_access_token}`}})).status(),404);
  // Simulated permission callback; no claim of real microphone capture.
  await page.evaluate(()=>{window.SpeechRecognition=class {start(){queueMicrotask(()=>this.onerror?.({error:'not-allowed'}));}stop(){this.onend?.();}};});
  await page.getByRole('button',{name:'Plan',exact:true}).click();
  await page.getByRole('button',{name:'Ask',exact:true}).click();
  await page.getByRole('button',{name:'Use microphone'}).click();
  await page.getByRole('status').filter({hasText:'Voice input unavailable. Type your question below.'}).waitFor();
  assert(await page.getByLabel('Your question').isEnabled());
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  assert.deepEqual(errors,[]);
  console.log('PASS live typed Ask; trace access/deletion; voice unavailable/denied fallback; keyboard skip link; mobile layout');
} finally {await browser.close();}
